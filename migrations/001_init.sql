-- Visitor analytics schema.
-- Column comments mark each field as OBSERVED (seen by the server), REPORTED (sent by
-- the browser and therefore client-controlled), or INFERRED (derived/estimated).

CREATE TABLE visits (
  id                 uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  session_id         uuid NOT NULL UNIQUE,          -- random id generated by the tracker
  visitor_id         uuid,                          -- first-party random id, only with consent
  consent_state      text NOT NULL,                 -- 'granted' | 'not-required'
  started_at         timestamptz NOT NULL,          -- OBSERVED: server receive time of first event
  last_seen_at       timestamptz NOT NULL,

  -- OBSERVED by the server
  ip                 text,                          -- NULL = unknown
  ip_source          text NOT NULL,                 -- how the IP was determined
  user_agent         text,
  accept_language    text,

  -- REPORTED by the browser
  landing_path       text NOT NULL,
  referrer_origin    text,
  languages          jsonb,
  time_zone          text,
  screen_width       integer,
  screen_height      integer,
  viewport_width     integer,
  viewport_height    integer,
  max_touch_points   integer,
  webdriver          boolean,

  -- INFERRED from the User-Agent string
  browser_name       text,
  browser_version    text,
  os_name            text,
  os_version         text,
  device_category    text NOT NULL DEFAULT 'unknown'
                     CHECK (device_category IN ('mobile', 'tablet', 'desktop', 'unknown')),
  is_bot             boolean NOT NULL DEFAULT false,
  bot_category       text,
  bot_reason         text,

  -- INFERRED by the IP lookup provider (estimates)
  enrichment_status  text NOT NULL DEFAULT 'pending',
  enrichment_source  text,
  enrichment_at      timestamptz,
  enrichment_error   text,
  geo_country_code   text,
  geo_country        text,
  geo_region         text,
  geo_city           text,
  net_isp            text,
  net_org            text,
  net_asn            text,
  net_vpn            boolean,                       -- NULL = provider gave no indicator
  net_proxy          boolean,
  net_tor            boolean,
  net_hosting        boolean
);

CREATE INDEX visits_started_at_idx ON visits (started_at DESC);
CREATE INDEX visits_visitor_idx ON visits (visitor_id);
CREATE INDEX visits_country_idx ON visits (geo_country_code);
CREATE INDEX visits_browser_idx ON visits (browser_name);
CREATE INDEX visits_device_idx ON visits (device_category);

CREATE TABLE events (
  id           bigserial PRIMARY KEY,
  event_id     uuid NOT NULL UNIQUE,                -- idempotency key from the tracker
  visit_id     uuid NOT NULL REFERENCES visits (id) ON DELETE CASCADE,
  type         text NOT NULL CHECK (type IN ('pageview', 'click')),
  name         text,                                -- developer-defined click event name
  label        text,                                -- developer-defined label (never typed text)
  path         text NOT NULL,                       -- REPORTED, sanitized
  occurred_at  timestamptz,                         -- REPORTED client clock (may be wrong)
  received_at  timestamptz NOT NULL                 -- OBSERVED server clock
);

CREATE INDEX events_visit_idx ON events (visit_id);
CREATE INDEX events_received_idx ON events (received_at DESC);
CREATE INDEX events_path_idx ON events (path);

CREATE TABLE settings (
  key    text PRIMARY KEY,
  value  jsonb NOT NULL
);

CREATE TABLE rate_limits (
  key           text NOT NULL,                      -- salted hash, never a raw IP
  window_start  timestamptz NOT NULL,
  count         integer NOT NULL,
  PRIMARY KEY (key, window_start)
);

CREATE TABLE ip_lookup_cache (
  ip           text PRIMARY KEY,
  provider     text NOT NULL,
  data         jsonb NOT NULL,
  looked_up_at timestamptz NOT NULL
);

-- Aggregate counters for crawlers and link previewers that fetch pages but usually do
-- not run JavaScript. No IPs or identifiers are stored here.
CREATE TABLE automated_hits (
  day       date NOT NULL,
  category  text NOT NULL,
  agent     text NOT NULL,
  path      text NOT NULL,
  hits      integer NOT NULL DEFAULT 0,
  PRIMARY KEY (day, category, agent, path)
);
